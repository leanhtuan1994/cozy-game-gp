/// <reference types="node" />
// Generates levels and writes one JSON file per level.
//
//   bun scripts/generate-levels.ts --all
//     Every chapter in src/engine/levels/chapterTemplates.ts, with its masks from
//     assets/items/<chapter>/masks.json, into src/engine/levels/data/, plus data/index.ts.
//
//   bun scripts/generate-levels.ts --zone <zone.json> --masks <masks.json> --chapter <id> \
//     [--chapter-index 0] [--levels 10] --out <dir>
//     One chapter on any zone (used for the fixture zones in tests and reports).
//
// Difficulty follows curveDifficulty(chapterIndex, levelIndex), and the last level is kept the
// chapter's hardest. Every level is checked by the solver before it is written; the run fails if
// any level cannot be made solvable inside its zone.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

import { CHAPTERS } from "../src/engine/levels/chapterTemplates";
import { PlacementZoneSchema, type PlacementZone } from "../src/engine/levels/zones";
import { generateChapter } from "../src/engine/puzzle/generator";
import type { LevelDef, MaskSet } from "../src/engine/puzzle/types";

const DATA_DIR = "src/engine/levels/data";

const { values } = parseArgs({
  options: {
    all: { type: "boolean", default: false },
    zone: { type: "string" },
    masks: { type: "string" },
    chapter: { type: "string" },
    "chapter-index": { type: "string", default: "0" },
    levels: { type: "string", default: "10" },
    out: { type: "string" },
  },
});

const readJson = (path: string) => JSON.parse(readFileSync(path, "utf8"));

function writeChapter(out: string, chapter: string, chapterIndex: number, zone: PlacementZone, masks: MaskSet, kinds: readonly string[], count: number): LevelDef[] {
  const levels = generateChapter({ chapter, chapterIndex, levels: count, zone, kinds, masks });
  for (const level of levels) {
    writeFileSync(join(out, `${level.id}.json`), `${JSON.stringify(level, null, 2)}\n`);
    console.log(`${level.id}: ${level.items.length} items, target ${level.target}, loss rate ${level.metrics?.lossRate}`);
  }
  return levels;
}

if (values.all) {
  rmSync(DATA_DIR, { recursive: true, force: true });
  mkdirSync(DATA_DIR, { recursive: true });
  // The index follows CHAPTERS order (play order), never the directory listing.
  const files = CHAPTERS.flatMap((chapter, chapterIndex) => {
    const masks = readJson(`assets/items/${chapter.id}/masks.json`) as MaskSet;
    return writeChapter(DATA_DIR, chapter.id, chapterIndex, chapter.zone, masks, chapter.kinds, Number(values.levels)).map((level) => `${level.id}.json`);
  });
  const imports = files.map((name, i) => `import level${i} from "./${name}";`).join("\n");
  writeFileSync(
    join(DATA_DIR, "index.ts"),
    `// Generated by scripts/generate-levels.ts --all. Do not edit by hand.\n${imports}\n\n` +
      `// Raw level JSON in play order; parse each with LevelDefSchema before use.\n` +
      `export const LEVEL_DATA: readonly unknown[] = [${files.map((_, i) => `level${i}`).join(", ")}];\n`,
  );
} else {
  if (!values.zone || !values.masks || !values.chapter || !values.out) {
    console.error("usage: bun scripts/generate-levels.ts --all | --zone <file> --masks <file> --chapter <id> [--chapter-index n] [--levels n] --out <dir>");
    process.exit(1);
  }
  const zone = PlacementZoneSchema.parse(readJson(values.zone));
  const masks = readJson(values.masks) as MaskSet;
  mkdirSync(values.out, { recursive: true });
  writeChapter(values.out, values.chapter, Number(values["chapter-index"]), zone, masks, Object.keys(masks).sort(), Number(values.levels));
}
